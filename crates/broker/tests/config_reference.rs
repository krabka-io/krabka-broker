#[cfg(test)]
#[rstest_bdd_macros::then("config reference: schema names the top level sections")]
fn bdd_verify_schema_names_the_top_level_sections() {
    let schema = file_config::config_schema();
    let properties = schema["properties"]
        .as_object()
        .expect("FileConfig schema has properties");
    for section in [
        "listeners",
        "tls_config",
        "oauthbearer",
        "gssapi",
        "authorization",
        "audit",
        "remote_storage",
        "operator_keys",
        "controller_quorum_voters",
        "runtime",
    ] {
        assert!(
            properties.contains_key(section),
            "FileConfig schema lost the `{section}` key"
        );
    }
}

