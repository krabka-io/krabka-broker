/// Every key the schema knows, as the bare key name a reference row carries.
fn schema_keys(schema: &Value) -> Vec<String> {
    fn walk(root: &Value, node: &Value, out: &mut Vec<String>) {
        let node = node
            .get("$ref")
            .and_then(Value::as_str)
            .map_or(node, |reference| {
                let name = reference
                    .strip_prefix("#/$defs/")
                    .expect("schemars emits local $defs refs");
                &root["$defs"][name]
            });
        if let Some(properties) = node.get("properties").and_then(Value::as_object) {
            for (key, field) in properties {
                out.push(key.clone());
                walk(root, field, out);
            }
        }
        for branch_list in ["anyOf", "oneOf"] {
            if let Some(branches) = node.get(branch_list).and_then(Value::as_array) {
                for branch in branches {
                    walk(root, branch, out);
                }
            }
        }
        if let Some(items) = node.get("items") {
            walk(root, items, out);
        }
    }
    let mut keys = Vec::new();
    walk(schema, schema, &mut keys);
    keys.sort();
    keys.dedup();
    keys
}

#[cfg(test)]
#[rstest_bdd_macros::then("config reference: reference page carries every schema key")]
fn bdd_verify_reference_page_carries_every_schema_key() {
    let path = repo_root().join("docs/config-reference.md");
    let page = fs::read_to_string(&path)
        .unwrap_or_else(|error| panic!("read {}: {error}", path.display()));
    assert!(
        page.contains("<!-- Generated by `aspect generate-config-reference`"),
        "docs/config-reference.md must carry the generated banner"
    );
    let missing: Vec<String> = schema_keys(&checked_in_schema())
        .into_iter()
        .filter(|key| !page.contains(&format!("| `{key}` |")))
        .collect();
    assert!(
        missing.is_empty(),
        "docs/config-reference.md has no row for {missing:?}: run \
         `aspect generate-config-reference`"
    );
}

