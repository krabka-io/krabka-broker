//! The checked-in config schema and reference page track `FileConfig`.
//!
//! `docs/config-schema.json` is what `krabka-broker --print-config-schema`
//! prints, and `docs/config-reference.md` is what
//! `aspect generate-config-reference` renders from it. The docs CI job
//! regenerates the page and diffs it, but that job has no Rust toolchain, so
//! the schema itself is compared here: a `FileConfig` change that is not
//! followed by a regeneration fails this suite.
#![cfg(test)]

