//! The checked-in config schema and reference page track `FileConfig`.
//!
//! `docs/config-schema.json` is what `krabka-broker --print-config-schema`
//! prints, and `docs/config-reference.md` is what
//! `aspect generate-config-reference` renders from it. The docs CI job
//! regenerates the page and diffs it, but that job has no Rust toolchain, so
//! the schema itself is compared here: a `FileConfig` change that is not
//! followed by a regeneration fails this suite.
#![cfg(test)]

use {
    assert2::assert,
    krabka_broker::file_config,
    rstest::fixture,
    rstest_bdd_macros::{given, scenarios, then, when},
    serde_json::Value,
    std::{
        env,
        ffi::OsString,
        fs,
        process::{Command, Output},
    },
};

#[path = "support/repository.rs"]
mod repository;
use repository::{checked_in_schema, repo_root};

/// Every key the schema knows, as the bare key name a reference row carries.
fn schema_keys(schema: &Value) -> Vec<String> {
    fn walk(root: &Value, node: &Value, out: &mut Vec<String>) {
        let node = node
            .get("$ref")
            .and_then(Value::as_str)
            .map_or(node, |reference| {
                let name = reference
                    .strip_prefix("#/$defs/")
                    .expect("schemars emits local $defs refs");
                &root["$defs"][name]
            });
        if let Some(properties) = node.get("properties").and_then(Value::as_object) {
            for (key, field) in properties {
                out.push(key.clone());
                walk(root, field, out);
            }
        }
        for branch_list in ["anyOf", "oneOf"] {
            if let Some(branches) = node.get(branch_list).and_then(Value::as_array) {
                for branch in branches {
                    walk(root, branch, out);
                }
            }
        }
        if let Some(items) = node.get("items") {
            walk(root, items, out);
        }
    }
    let mut keys = Vec::new();
    walk(schema, schema, &mut keys);
    keys.sort();
    keys.dedup();
    keys
}

#[derive(Default)]
struct ConfigurationReference {
    checked_in: Option<Value>,
    generated: Option<Value>,
    page: Option<String>,
    executable: Option<OsString>,
    output: Option<Output>,
}

#[fixture]
fn reference() -> ConfigurationReference {
    // Start this scenario with fresh inputs and observations.

    ConfigurationReference {
        checked_in: None,
        generated: None,
        page: None,
        executable: None,
        output: None,
    }
}

#[given("the checked-in configuration schema and reference page")]
fn checked_in_reference(reference: &mut ConfigurationReference) {
    reference.checked_in = Some(checked_in_schema());
    let path = repo_root().join("docs/config-reference.md");
    reference.page = Some(
        fs::read_to_string(&path)
            .unwrap_or_else(|error| panic!("read {}: {error}", path.display())),
    );
}

#[given("the broker executable and its library configuration schema")]
fn broker_executable(reference: &mut ConfigurationReference) {
    reference.executable = Some(
        env::var_os("CARGO_BIN_EXE_krabka-broker")
            .expect("cargo and the Bazel target both export CARGO_BIN_EXE_krabka-broker"),
    );
    reference.generated = Some(file_config::config_schema());
}

#[when("the FileConfig schema is generated")]
fn generate_schema(reference: &mut ConfigurationReference) {
    reference.generated = Some(file_config::config_schema());
}

#[when("the broker is invoked with --print-config-schema")]
fn print_schema(reference: &mut ConfigurationReference) {
    reference.output = Some(
        Command::new(reference.executable.as_ref().expect("a broker executable"))
            .arg("--print-config-schema")
            .output()
            .expect("spawn krabka-broker"),
    );
}

#[then("the generated schema matches the checked-in schema")]
fn checked_in_schema_matches(reference: &ConfigurationReference) {
    let generated = reference.generated.as_ref().expect("a generated schema");
    let checked_in = reference.checked_in.as_ref().expect("a checked-in schema");
    assert!(
        generated == checked_in,
        "docs/config-schema.json is stale: run `krabka-broker --print-config-schema > \
         docs/config-schema.json` and then `aspect generate-config-reference`"
    );
}

#[then("the reference page has a generated banner and a row for every schema key")]
fn reference_covers_schema(reference: &ConfigurationReference) {
    let page = reference
        .page
        .as_ref()
        .expect("the reference page was loaded");
    assert!(
        page.contains("<!-- Generated by `aspect generate-config-reference`"),
        "docs/config-reference.md must carry the generated banner"
    );
    let missing: Vec<String> =
        schema_keys(reference.checked_in.as_ref().expect("a checked-in schema"))
            .into_iter()
            .filter(|key| !page.contains(&format!("| `{key}` |")))
            .collect();
    assert!(
        missing.is_empty(),
        "docs/config-reference.md has no row for {missing:?}: run `aspect generate-config-reference`"
    );
}

#[then("the command succeeds and prints the library schema as JSON")]
fn printed_schema(reference: &ConfigurationReference) {
    let output = reference
        .output
        .as_ref()
        .expect("the schema command was run");
    assert!(
        output.status.success(),
        "krabka-broker --print-config-schema failed: {}",
        String::from_utf8_lossy(&output.stderr)
    );
    let printed: Value =
        serde_json::from_slice(&output.stdout).expect("--print-config-schema prints JSON");
    assert!(&printed == reference.generated.as_ref().expect("the library schema"));
}

#[then("the schema exposes every operator configuration section")]
fn operator_sections(reference: &ConfigurationReference) {
    let schema = reference.generated.as_ref().expect("a generated schema");
    let properties = schema["properties"]
        .as_object()
        .expect("FileConfig schema has properties");
    for section in [
        "listeners",
        "tls_config",
        "oauthbearer",
        "gssapi",
        "authorization",
        "audit",
        "remote_storage",
        "operator_keys",
        "controller_quorum_voters",
        "runtime",
    ] {
        assert!(
            properties.contains_key(section),
            "FileConfig schema lost the `{section}` key"
        );
    }
}

#[then("duration and byte-size fields advertise their units")]
fn field_units(reference: &ConfigurationReference) {
    let schema = reference.generated.as_ref().expect("a generated schema");
    let runtime = &schema["$defs"]["RuntimeFileConfig"]["properties"];
    for (key, format) in [
        ("heartbeat_interval", "duration"),
        ("log_segment_bytes", "byte-size"),
    ] {
        assert!(
            runtime[key]["format"] == format,
            "[runtime] {key} should carry format {format}, got {}",
            runtime[key]
        );
    }
    assert!(schema["properties"]["heartbeat_interval"]["format"] == "duration");
}

