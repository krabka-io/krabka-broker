//! Which `\p{name}` and `\P{name}` names Java's `Pattern` takes.
//!
//! `fancy_regex` matches a property name loosely: in any case, with or
//! without spaces, underscores and hyphens, and for every Unicode property and
//! script it knows. `Pattern.family` takes fewer, each in one spelling, and
//! refuses the rest with `Unknown character property name`. [`java_knows`]
//! says which it takes, so that the rewrite refuses a name Java refuses
//! instead of matching it as `fancy_regex` reads it. A name Java takes and
//! `fancy_regex` does not, such as a Unicode block, still fails to compile.
//!
//! The tables are those of JDK 25's `CharPredicates` and
//! `Character.UnicodeScript`.

/// Whether Java's `Pattern.family` takes `name`, the text between the braces
/// of `\p{name}`, or the letter of `\pL`. `unicode_classes` is `(?U)`.
///
/// - `key=value`: `sc` or `script` with a script, `gc` or
///   `general_category` with a name `forProperty` takes, and `blk` or
///   `block` with a block. The key is in any case.
/// - `In` and a block.
/// - `Is` and a Unicode property or POSIX class in any case
///   (`forUnicodeProperty`), a name `forProperty` takes, or a script.
/// - Otherwise a POSIX class in any case under `(?U)`, or a name
///   `forProperty` takes.
///
/// Every block name is taken here: `fancy_regex` knows none, so a block
/// fails to compile whatever its name.
pub(super) fn java_knows(name: &str, unicode_classes: bool) -> bool {
    if let Some((key, value)) = name.split_once('=') {
        return match key.to_lowercase().as_str() {
            "sc" | "script" => is_script(value),
            "gc" | "general_category" => FOR_PROPERTY.contains(&value),
            "blk" | "block" => true,
            _ => false,
        };
    }
    if name.starts_with("In") {
        return true;
    }
    if let Some(short) = name.strip_prefix("Is") {
        let upper = short.to_uppercase();
        return UNICODE_PROPERTIES.contains(&upper.as_str())
            || POSIX_NAMES.contains(&upper.as_str())
            || FOR_PROPERTY.contains(&short)
            || is_script(short);
    }
    (unicode_classes && POSIX_NAMES.contains(&name.to_uppercase().as_str()))
        || FOR_PROPERTY.contains(&name)
}

/// `Character.UnicodeScript.forName`: the name of a script or its alias, in
/// any case.
fn is_script(name: &str) -> bool { SCRIPTS.binary_search(&name.to_uppercase().as_str()).is_ok() }

